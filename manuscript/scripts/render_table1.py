"""Render `manuscript/derived/table1.json` (from `table1.py`) as Markdown.
Standard library only:

    python3 -I manuscript/scripts/render_table1.py manuscript/derived/table1.json \
      > manuscript/derived/table1.md
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

COLUMNS = [
    ("all_ingested", "All records"),
    ("review_queue", "Clinician review set"),
    ("holdout", "Ablation holdout"),
    ("holdout_analysed", "Ablation analysed"),
    ("holdout_excluded_no_gold", "Excluded, no gold set"),
]
CONTINUOUS = [
    ("day_of_life", "Day of life", "{:.0f}"),
    ("gestational_age_weeks", "Gestational age, weeks", "{:.1f}"),
    ("birth_weight_g", "Birth weight, g", "{:.0f}"),
    ("temperature_c", "Temperature, °C", "{:.1f}"),
    ("heart_rate_bpm", "Heart rate, /min", "{:.0f}"),
    ("resp_rate_bpm", "Respiratory rate, /min", "{:.0f}"),
    ("spo2_percent", "SpO2, %", "{:.0f}"),
]
CATEGORICAL = [
    ("sex", "Sex"),
    ("triage_category", "Triage category"),
    ("care_setting", "Care setting"),
]


def cont(s: dict, fmt: str) -> str:
    if not s.get("n"):
        return "—"
    cell = f"{fmt.format(s['median'])} ({fmt.format(s['q1'])}–{fmt.format(s['q3'])})"
    return cell + (f" [{s['missing']} missing]" if s["missing"] else "")


def cat(c: dict | None) -> str:
    if c is None:
        return "0"
    if c["pct"] is None:
        return str(c["n"])
    return f"{c['n']} ({c['pct']:.2f})"


def main(argv: list[str]) -> int:
    d = json.loads(Path(argv[1]).read_text(encoding="utf-8"))
    sets = d["sets"]
    o = [
        "<!-- generated by manuscript/scripts/render_table1.py; do not edit by hand -->",
        "",
        "| Characteristic | "
        + " | ".join(f"{lab} (n = {sets[k]['n_records']})" for k, lab in COLUMNS)
        + " |",
        "|---" * (len(COLUMNS) + 1) + "|",
    ]
    for key, label, fmt in CONTINUOUS:
        o.append(
            f"| {label}, median (IQR) | "
            + " | ".join(cont(sets[k][key], fmt) for k, _ in COLUMNS)
            + " |"
        )
    for key, label in CATEGORICAL:
        o.append(f"| **{label}, n (%)** |" + " |" * len(COLUMNS))
        levels: list[str] = []
        for k, _ in COLUMNS:
            for level in sets[k][key]:
                if level not in levels:
                    levels.append(level)
        for level in levels:
            o.append(
                f"| {level} | "
                + " | ".join(cat(sets[k][key].get(level)) for k, _ in COLUMNS)
                + " |"
            )
    o += [
        "",
        "Exact counts, no small-cell suppression. Vital signs are the first recorded set.",
    ]
    print("\n".join(o))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
