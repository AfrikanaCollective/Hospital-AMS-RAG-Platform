"""Render Additional file 2: the prompt templates the pipeline sent to the
language model, copied verbatim from `backend/app/agents/prompts/`.

Only the two templates the answer path loads are included
(`guideline_synthesis_agent.py`, `citation_verifier_agent.py`); the scope,
stage and missing-information templates exist in the repository but are
never loaded. Each file is reproduced byte for byte, HTML comments
included, because the whole file is what the model receives. Standard
library only:

    python3 -I manuscript/scripts/render_prompts_appendix.py \
      > manuscript/06_supplement_S2_prompts.md
"""

from __future__ import annotations

import hashlib
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
PROMPTS = REPO / "backend" / "app" / "agents" / "prompts"

TEMPLATES = [
    (
        "guideline_synthesis.md",
        "S2.1 Guideline synthesis",
        "Sent once per question. The placeholders were filled as follows: "
        "`{{question}}` with the generated question; `{{sources}}` with the retrieved "
        "passages, each labelled `[c1]`, `[c2]`, … with its document title, version, "
        "section and pages, followed by its text; `{{feature_summary}}`, "
        "`{{scope2_context}}` and `{{hospital_constraint}}` with the attached patient "
        "features, stage or missing-information context and hospital constraint. "
        "No patient record or constraint was attached to the study questions, so "
        "these three were empty (`{}`, blank, blank). If the filled prompt would exceed "
        "the context budget, passages were dropped, lowest re-ranker score first, with "
        "each guideline keeping its last passage until every guideline was down to one.",
    ),
    (
        "citation_verifier.md",
        "S2.2 Citation verification (entailment)",
        "Used for a claim that passed the deterministic citation and verbatim-quote "
        "checks, and only when the share of the claim's content words found in its "
        "quote was inconclusive (above 0.05 and below 0.75). At 0.75 or more the claim "
        "was taken as supported, and at 0.05 or less as unsupported, without a model "
        "call (`GROUNDING_ENTAILMENT_MODE=hybrid`). `{{claim}}` was the claim text and "
        "`{{passage}}` the claim's verbatim quote. This is the only model call in the "
        "grounding gate.",
    ),
]


def _git_last_change(path: Path) -> str:
    out = subprocess.run(
        [
            "git",
            "-C",
            str(REPO),
            "log",
            "-1",
            "--format=%h %ad",
            "--date=short",
            "--",
            str(path),
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    return out.stdout.strip() or "unknown"


def main() -> int:
    o = [
        "# Additional file 2 — Prompt templates (S2)",
        "",
        "<!-- generated by manuscript/scripts/render_prompts_appendix.py; do not edit by hand -->",
        "",
        "The pipeline sent each prompt to the language model as a single user message "
        "with an empty system prompt. The templates were written during platform "
        "development and were not tuned on the study records. They are reproduced "
        "verbatim below, including the HTML comments at the top of each file, because "
        "the whole file was sent. Placeholders in double braces were filled at run time. "
        "The repository also holds templates for scope classification, stage "
        "classification and missing-information requests; the answer path did not load "
        "them (scope classification was deterministic), so they are not shown.",
        "",
    ]
    for name, heading, note in TEMPLATES:
        path = PROMPTS / name
        text = path.read_text(encoding="utf-8")
        digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
        o += [
            f"## {heading}",
            "",
            note,
            "",
            f"File `backend/app/agents/prompts/{name}`; last changed in commit "
            f"{_git_last_change(path)}; SHA-256 `{digest[:16]}…`.",
            "",
            "````markdown",
            text.rstrip("\n"),
            "````",
            "",
        ]
    print("\n".join(o))
    return 0


if __name__ == "__main__":
    sys.exit(main())
