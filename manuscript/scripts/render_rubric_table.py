"""Render Additional file 1, Table S1: the rating instrument as raters see
it — the 11 PATH rubric domains (`app.rubric.domains.RUBRIC_DOMAINS`,
verified verbatim against the PATH LLM Playbook on 2026-10-26) and the
triage-agreement item (`app.eval.triage`) with the attested mortality
figures (`data/triage_mortality.yaml`, through the platform's own loader).
Nothing is retyped. Markdown on stdout.

    docker compose run --rm --no-deps -T -e PYTHONPATH=/app \
      -v ./backend/app:/app/app:ro -v ./manuscript/scripts:/app/manuscript_scripts:ro \
      -v ./data/triage_mortality.yaml:/app/data/triage_mortality.yaml:ro \
      api python manuscript_scripts/render_rubric_table.py \
      | sed -n '/^<!--/,$p' > manuscript/derived/table_s1_rubric.md
"""

from __future__ import annotations

import sys

from app.config import get_settings
from app.eval.triage import _NARRATIVE, TRIAGE_AGREEMENT_DOMAIN, load_triage_mortality
from app.rubric.domains import RUBRIC_DOMAINS


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def main() -> int:
    table = load_triage_mortality(get_settings().triage_mortality_path)
    o = [
        "<!-- generated by manuscript/scripts/render_rubric_table.py; do not edit by hand -->",
        "",
        "**Table S1. Rating instrument.** Domains 1–11 are the PATH LLM evaluation rubric, "
        "with its definitions and anchors verbatim. Every domain is scored 1–5, where 1 is "
        "always the worst rating and 5 the best; for domains 7 and 8 the anchor labels run "
        "from severe or very high harm (1) to none or very low (5). The triage-agreement "
        "item was asked on assessment items only.",
        "",
        "| # | Domain | Definition | 1 | 2 | 3 | 4 | 5 |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for d in RUBRIC_DOMAINS:
        o.append(
            f"| {d.ordinal} | {cell(d.name)} | {cell(d.definition)} | "
            + " | ".join(cell(a) for a in d.anchors)
            + " |"
        )
    t = TRIAGE_AGREEMENT_DOMAIN
    o.append(
        f"| T | {cell(t.name)} | {cell(t.definition)} | "
        + " | ".join(cell(a) for a in t.anchors)
        + " |"
    )
    o += [
        "",
        "Triage-agreement item, as shown to raters (the category, source and mortality "
        "figure are filled in per item):",
        "",
        "> "
        + _NARRATIVE.format(
            category="<category>", citation="<source>", mortality="<mortality rate>"
        ),
        "",
        "Mortality shown by category (in-hospital mortality of each cluster in the "
        "development cohort of Tuti et al. 2026, rounded): "
        + ", ".join(f"{c} {m}" for c, m in table.mortality.items())
        + ".",
    ]
    print("\n".join(o))
    return 0


if __name__ == "__main__":
    sys.exit(main())
